/**
 * invoke-anthropic.mjs
 *
 * This module formats the prompt, calls the Anthropic Claude LLM, handles and
 * formats the streamed response, and returns a results object.
 */
import Anthropic from "@anthropic-ai/sdk";

const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

export async function invokeAnthropic(promptObj) {

  const cleanMessages = [];
  
  for (let i = 0; i < promptObj.messages.length; i++) {
    const msg = promptObj.messages[i];
    
    if (msg.role === 'tool') {
      // Tool results must be part of a user message with tool_result content blocks
      const toolResult = {
        role: 'user',
        content: [
          {
            type: 'tool_result',
            tool_use_id: msg.tool_call_id,
            content: typeof msg.content === 'string' ? msg.content : JSON.stringify(msg.content)
          }
        ]
      };
      cleanMessages.push(toolResult);
    } else {
      // Regular messages - handle both string content and Anthropic content blocks
      if (Array.isArray(msg.content)) {
        cleanMessages.push({
          role: msg.role,
          content: msg.content
        });
      } else {
        cleanMessages.push({
          role: msg.role,
          content: msg.content
        });
      }
    }
  }

  // SET THE PROMPT TO ANTHROPIC
  const prompt = {
    messages: cleanMessages,
    model: promptObj.sessionDetails.llmModel, // Set as env var or override in session details
    max_tokens: 1024,
    stream: true,
  };

  // Extract system prompt from messages if present (Anthropic handles them separately)
  const systemMessages = cleanMessages.filter(msg => msg.role === 'system');
  if (systemMessages.length > 0) {
    prompt.system = systemMessages[systemMessages.length - 1].content;
    prompt.messages = cleanMessages.filter(msg => msg.role !== 'system');
  }

  // Provide the tools available for the LLM to call
  if (!promptObj.toolCallCompletion && promptObj.sessionDetails.tools) {
    const openAITools = JSON.parse(promptObj.sessionDetails.tools);
    if (openAITools && openAITools.length > 0) {
      // Convert OpenAI tool format to Anthropic format
      const anthropicTools = openAITools.map(tool => ({
        name: tool.function.name,
        description: tool.function.description,
        input_schema: tool.function.parameters
      }));
      prompt.tools = anthropicTools;
    }
  }

  // Instantiate the object that LLM returns.
  let returnObj = {};
  returnObj.role = "assistant";
  returnObj.content = "";
  returnObj.tool_calls = {};
  returnObj.refusal = null;


  try {
    // call Anthropic and wait for response...
    const stream = await anthropic.messages.create(prompt);

    const assistantSegments = [];

    // Iterate over stream
    for await (const chunk of stream) {
      
      /**
       *
       * INTERRUPTION HANDLING
       *
       * ConversationRelay handles interruptions.
       * If additional interruption handling is needed,
       * it could be handled here by periodically
       * checking a session flag that gets set on
       * an interruption generated by a SEPARATE event.
       * Again, ConversationRelay has interruption handling
       * so additional logic likely is not needed but it could
       * be done here.
       *
       */

      // Handle text content streaming
      if (chunk.type === 'content_block_delta' && chunk.delta.type === 'text_delta') {
        const content = chunk.delta.text;

        // Send content (current chunk content) back to WebSocket & Twilio for TTS
        promptObj.socket.send(
          JSON.stringify({
            type: "text",
            token: content,
            last: false,
          })
        );

        if (promptObj.clientSocket !== null) {
          promptObj.clientSocket.send(
            JSON.stringify({
              type: "text",
              token: content,
              last: false,
            })
          );
        }

        // Record details from current chunk
        returnObj.content += content;
        assistantSegments.push(content);
      }

      // Handle tool use blocks
      if (chunk.type === 'content_block_start' && chunk.content_block.type === 'tool_use') {
        const toolCall = chunk.content_block;

        // Add tool call to return object in OpenAI-compatible format
        returnObj.tool_calls[toolCall.id] = {
          id: toolCall.id,
          type: "function",
          function: {
            name: toolCall.name,
            arguments: JSON.stringify(toolCall.input || {}),
          },
        };

        // Store the Anthropic tool_use block for conversation history
        if (!returnObj.anthropic_tool_uses) {
          returnObj.anthropic_tool_uses = [];
        }
        returnObj.anthropic_tool_uses.push({
          type: "tool_use",
          id: toolCall.id,
          name: toolCall.name,
          input: toolCall.input || {}
        });

        returnObj.finish_reason = "tool_calls";
      }

      // Handle message completion
      if (chunk.type === 'message_delta' && chunk.delta.stop_reason) {
        returnObj.finish_reason = chunk.delta.stop_reason;
      }
    }

    // Send final completion signal
    promptObj.socket.send(
      JSON.stringify({
        type: "text",
        token: "",
        last: true,
      })
    );

    // Set completion flag
    returnObj.last = true;

    // If no tool calls were made, ensure finish_reason is set
    if (!returnObj.finish_reason) {
      returnObj.finish_reason = "stop";
    }

  } catch (error) {
    console.error("Error in invokeAnthropic: ", error);
    
    // Send error message to user
    promptObj.socket.send(
      JSON.stringify({
        type: "text",
        token: "I apologize, but I'm experiencing technical difficulties. Please try again.",
        last: true,
      })
    );
    
    throw error;
  }


  return returnObj;
}